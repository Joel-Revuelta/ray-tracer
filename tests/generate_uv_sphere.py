#!/usr/bin/env python3
"""Generate a UV sphere OBJ for mesh benchmarks."""

from __future__ import annotations

import math
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 4:
        print(f"usage: {sys.argv[0]} <segments> <rings> <output.obj>", file=sys.stderr)
        return 2

    segments = int(sys.argv[1])
    rings = int(sys.argv[2])
    output = Path(sys.argv[3])

    if segments < 3 or rings < 2:
        print("segments must be >= 3 and rings must be >= 2", file=sys.stderr)
        return 2

    vertices = []
    for ring in range(rings + 1):
        theta = math.pi * ring / rings
        sin_theta = math.sin(theta)
        cos_theta = math.cos(theta)
        for segment in range(segments):
            phi = 2.0 * math.pi * segment / segments
            vertices.append((
                sin_theta * math.cos(phi),
                cos_theta,
                sin_theta * math.sin(phi),
            ))

    faces = []
    for ring in range(rings):
        for segment in range(segments):
            next_segment = (segment + 1) % segments
            a = ring * segments + segment
            b = ring * segments + next_segment
            c = (ring + 1) * segments + next_segment
            d = (ring + 1) * segments + segment
            faces.append((a, b, c))
            faces.append((a, c, d))

    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as handle:
        handle.write("# Generated by tests/generate_uv_sphere.py\n")
        for x, y, z in vertices:
            handle.write(f"v {x:.8f} {y:.8f} {z:.8f}\n")
        for ring in range(rings + 1):
            for segment in range(segments):
                handle.write(f"vt {segment / segments:.8f} {ring / rings:.8f}\n")
        for x, y, z in vertices:
            handle.write(f"vn {x:.8f} {y:.8f} {z:.8f}\n")
        for a, b, c in faces:
            handle.write(f"f {a + 1}/{a + 1}/{a + 1} {b + 1}/{b + 1}/{b + 1} {c + 1}/{c + 1}/{c + 1}\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
