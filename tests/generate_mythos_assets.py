#!/usr/bin/env python3
"""Generate the deterministic meshes and HDR skies used by the MYTHOS scenes."""

from __future__ import annotations

import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "scenes" / "models"
TEXTURES = ROOT / "scenes" / "textures"


def normalize(vector: tuple[float, float, float]) -> tuple[float, float, float]:
    length = math.sqrt(sum(component * component for component in vector))

    return tuple(component / length for component in vector)


def write_obj(path: Path, name: str, vertices: list[tuple[float, float, float]],
              faces: list[tuple[int, ...]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as handle:
        handle.write("# Generated by tests/generate_mythos_assets.py\n")
        handle.write(f"o {name}\n")

        for x, y, z in vertices:
            handle.write(f"v {x:.8f} {y:.8f} {z:.8f}\n")
        for face in faces:
            handle.write("f " + " ".join(str(index + 1) for index in face) + "\n")


def generate_shard() -> None:
    """An irregular crystal shard, one unit tall and centred at the origin."""
    rng = random.Random(7107)
    ring = []

    for index in range(7):
        angle = 2.0 * math.pi * index / 7.0
        radius = 0.22 + rng.uniform(-0.05, 0.09)
        ring.append((math.cos(angle) * radius, rng.uniform(-0.10, 0.12), math.sin(angle) * radius))

    vertices = [(0.0, 0.55, 0.0), (0.0, -0.55, 0.0)] + ring
    faces = []

    for index in range(7):
        next_index = (index + 1) % 7
        faces.append((0, 2 + index, 2 + next_index))
        faces.append((1, 2 + next_index, 2 + index))

    write_obj(MODELS / "shard.obj", "shard", vertices, faces)


def generate_petal() -> None:
    """A curved, tapered solid petal along +Z."""
    segments = 28
    ring_count = 10
    vertices = []
    rings = []

    for segment in range(segments + 1):
        t = segment / segments
        width = 0.08 + 0.62 * math.sin(math.pi * t) ** 0.65
        thickness = 0.012 + 0.022 * math.sin(math.pi * t)
        center_y = 0.34 * t * t
        ring = []

        for index in range(ring_count):
            angle = 2.0 * math.pi * index / ring_count
            x = math.cos(angle) * width
            y = center_y + math.sin(angle) * thickness
            z = t
            ring.append(len(vertices))
            vertices.append((x, y, z))
        rings.append(ring)

    faces = []

    for segment in range(segments):
        for index in range(ring_count):
            next_index = (index + 1) % ring_count
            a = rings[segment][index]
            b = rings[segment][next_index]
            c = rings[segment + 1][next_index]
            d = rings[segment + 1][index]
            faces.append((a, b, c, d))

    bottom = len(vertices)
    vertices.append((0.0, 0.0, 0.0))
    top = len(vertices)
    vertices.append((0.0, 0.34, 1.0))

    for index in range(ring_count):
        next_index = (index + 1) % ring_count
        faces.append((bottom, rings[0][next_index], rings[0][index]))
        faces.append((top, rings[-1][index], rings[-1][next_index]))

    write_obj(MODELS / "petal.obj", "petal", vertices, faces)


def to_rgbe(red: float, green: float, blue: float) -> tuple[int, int, int, int]:
    maximum = max(red, green, blue)

    if maximum < 1e-32:
        return 0, 0, 0, 0

    mantissa, exponent = math.frexp(maximum)
    scale = mantissa * 256.0 / maximum

    return (
        max(0, min(255, int(red * scale))),
        max(0, min(255, int(green * scale))),
        max(0, min(255, int(blue * scale))),
        max(0, min(255, exponent + 128)),
    )


def write_hdr(path: Path, width: int, height: int,
              pixels: list[tuple[float, float, float]]) -> None:
    header = f"#?RADIANCE\nFORMAT=32-bit_rle_rgbe\n\n-Y {height} +X {width}\n".encode("ascii")
    data = bytearray()

    for rgb in pixels:
        data.extend(to_rgbe(*rgb))

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(header + bytes(data))


def direction_at(x: int, y: int, width: int, height: int) -> tuple[float, float, float]:
    u = (x + 0.5) / width
    v = (y + 0.5) / height
    phi = v * math.pi
    theta = (u - 0.5) * 2.0 * math.pi
    sin_phi = math.sin(phi)

    return (sin_phi * math.cos(theta), math.cos(phi), sin_phi * math.sin(theta))


def generate_eclipse_sky() -> None:
    width, height = 1024, 512
    rng = random.Random(9203)
    pixels = []

    for y in range(height):
        for x in range(width):
            direction = direction_at(x, y, width, height)
            sky = math.sqrt(max(direction[1], 0.0))
            horizon = (0.020, 0.055, 0.075)
            zenith = (0.002, 0.006, 0.020)
            color = [horizon[channel] * (1.0 - sky) + zenith[channel] * sky for channel in range(3)]

            # Eclipse ring low on the horizon.
            ring_direction = normalize((0.10, 0.16, 0.98))
            cosine = sum(direction[i] * ring_direction[i] for i in range(3))
            ring = math.exp(-((1.0 - cosine) * 950.0)) * 2.4
            glow = math.exp(-((1.0 - cosine) * 22.0)) * 0.16
            for channel, strength in enumerate((0.65, 0.95, 1.25)):
                color[channel] += glow * strength + ring * (0.45 + 0.3 * strength)

            # Sparse cold stars.
            if direction[1] > 0.05 and rng.random() < 0.0008:
                brightness = rng.uniform(0.4, 1.6)
                color = [channel + brightness for channel in color]

            pixels.append(tuple(color))

    write_hdr(TEXTURES / "eclipse_sky.hdr", width, height, pixels)


def generate_aurora_sky() -> None:
    width, height = 1024, 512
    rng = random.Random(11311)
    pixels = []

    for y in range(height):
        for x in range(width):
            direction = direction_at(x, y, width, height)
            sky = math.sqrt(max(direction[1], 0.0))
            horizon = (0.015, 0.045, 0.070)
            zenith = (0.004, 0.010, 0.035)
            color = [horizon[channel] * (1.0 - sky) + zenith[channel] * sky for channel in range(3)]

            bands = math.sin(direction[0] * 7.0 + direction[2] * 4.0 + 1.7)
            bands += 0.55 * math.sin(direction[0] * 15.0 - direction[2] * 9.0 + 0.4)
            curtain = max(0.0, bands) ** 3.0 * max(0.0, direction[1]) ** 0.7
            color[0] += curtain * 0.05
            color[1] += curtain * 0.55
            color[2] += curtain * 0.45

            glow = math.exp(-((1.0 - direction[1]) * 8.0)) * 0.05
            color[0] += glow * 0.2
            color[1] += glow * 0.6
            color[2] += glow * 0.7

            if direction[1] > 0.08 and rng.random() < 0.0012:
                brightness = rng.uniform(0.3, 1.4)
                color = [channel + brightness for channel in color]

            pixels.append(tuple(color))

    write_hdr(TEXTURES / "aurora_sky.hdr", width, height, pixels)


def generate_forge_sky() -> None:
    width, height = 1024, 512
    rng = random.Random(14431)
    pixels = []

    for y in range(height):
        for x in range(width):
            direction = direction_at(x, y, width, height)
            sky = math.sqrt(max(direction[1], 0.0))
            horizon = (0.10, 0.035, 0.012)
            zenith = (0.010, 0.004, 0.006)
            color = [horizon[channel] * (1.0 - sky) + zenith[channel] * sky for channel in range(3)]

            cloud = math.sin(direction[0] * 9.0 + direction[2] * 5.0)
            cloud += 0.6 * math.sin(direction[0] * 21.0 - direction[2] * 13.0)
            cloud = max(0.0, cloud) ** 2.0 * max(0.0, direction[1]) ** 0.5
            color[0] += cloud * 0.55
            color[1] += cloud * 0.16
            color[2] += cloud * 0.04

            if direction[1] > 0.05 and rng.random() < 0.0006:
                brightness = rng.uniform(0.5, 1.8)
                color = [channel + brightness for channel in color]

            pixels.append(tuple(color))

    write_hdr(TEXTURES / "forge_sky.hdr", width, height, pixels)


def main() -> None:
    MODELS.mkdir(parents=True, exist_ok=True)
    TEXTURES.mkdir(parents=True, exist_ok=True)
    generate_shard()
    generate_petal()
    generate_eclipse_sky()
    generate_aurora_sky()
    generate_forge_sky()


if __name__ == "__main__":
    main()
