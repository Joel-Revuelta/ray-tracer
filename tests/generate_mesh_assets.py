#!/usr/bin/env python3
"""Generate the deterministic OBJ assets used by the mesh scenes."""

from __future__ import annotations

import math
from pathlib import Path


def icosphere(subdivisions: int) -> tuple[list[tuple[float, float, float]], list[tuple[int, int, int]]]:
    t = (1.0 + math.sqrt(5.0)) / 2.0
    vertices = [
        (-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0),
        (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
        (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1),
    ]
    vertices = [normalize(v) for v in vertices]
    faces = [
        (0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11),
        (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
        (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9),
        (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1),
    ]

    for _ in range(subdivisions):
        cache: dict[tuple[int, int], int] = {}
        next_faces: list[tuple[int, int, int]] = []

        def midpoint(a: int, b: int) -> int:
            key = (min(a, b), max(a, b))
            if key not in cache:
                va, vb = vertices[a], vertices[b]
                vertices.append(normalize(((va[0] + vb[0]) / 2, (va[1] + vb[1]) / 2, (va[2] + vb[2]) / 2)))
                cache[key] = len(vertices) - 1
            return cache[key]

        for a, b, c in faces:
            ab, bc, ca = midpoint(a, b), midpoint(b, c), midpoint(c, a)
            next_faces.extend([(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)])
        faces = next_faces

    return vertices, faces


def torus(major_segments: int, minor_segments: int, major_radius: float, minor_radius: float):
    vertices = []
    normals = []
    uvs = []
    for i in range(major_segments):
        theta = 2.0 * math.pi * i / major_segments
        ct, st = math.cos(theta), math.sin(theta)
        for j in range(minor_segments):
            phi = 2.0 * math.pi * j / minor_segments
            cp, sp = math.cos(phi), math.sin(phi)
            vertices.append((
                (major_radius + minor_radius * cp) * ct,
                minor_radius * sp,
                (major_radius + minor_radius * cp) * st,
            ))
            normals.append((cp * ct, sp, cp * st))
            uvs.append((i / major_segments, j / minor_segments))

    faces = []
    for i in range(major_segments):
        ni = (i + 1) % major_segments
        for j in range(minor_segments):
            nj = (j + 1) % minor_segments
            a = i * minor_segments + j
            b = ni * minor_segments + j
            c = ni * minor_segments + nj
            d = i * minor_segments + nj
            faces.append((a, b, c))
            faces.append((a, c, d))
    return vertices, faces, normals, uvs


def normalize(v: tuple[float, float, float]) -> tuple[float, float, float]:
    length = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2])
    return (v[0] / length, v[1] / length, v[2] / length)


def spherical_uv(vertex):
    x, y, z = vertex
    u = 0.5 + math.atan2(z, x) / (2.0 * math.pi)
    v = math.acos(max(-1.0, min(1.0, y))) / math.pi
    return (u, v)


def write_obj(path: Path, name: str, vertices, faces, normals, uvs) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        handle.write(f"# Generated by tests/generate_mesh_assets.py\n")
        handle.write(f"o {name}\n")
        for x, y, z in vertices:
            handle.write(f"v {x:.8f} {y:.8f} {z:.8f}\n")
        for u, v in uvs:
            handle.write(f"vt {u:.8f} {v:.8f}\n")
        for x, y, z in normals:
            handle.write(f"vn {x:.8f} {y:.8f} {z:.8f}\n")
        for a, b, c in faces:
            handle.write(f"f {a + 1}/{a + 1}/{a + 1} {b + 1}/{b + 1}/{b + 1} {c + 1}/{c + 1}/{c + 1}\n")


def main() -> None:
    root = Path(__file__).resolve().parent.parent / "scenes" / "models"
    icosphere_vertices, icosphere_faces = icosphere(2)
    icosphere_uvs = [spherical_uv(vertex) for vertex in icosphere_vertices]
    write_obj(root / "icosphere.obj", "icosphere", icosphere_vertices, icosphere_faces, icosphere_vertices,
              icosphere_uvs)
    write_obj(root / "torus.obj", "torus", *torus(32, 16, 1.0, 0.35))


if __name__ == "__main__":
    main()
